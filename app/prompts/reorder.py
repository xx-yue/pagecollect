ORDER_USER_TEMPLATE = """以下是同一份材料的 {total} 页摘要。每一行的方括号内是该页的物理编号（无意义）：

{pages_block}

请推断正确的阅读顺序，输出完整的 {total} 个物理编号。"""


def build_pages_block(pages) -> str:
    """把 PageInfo 列表拼成给模型看的紧凑文本块。

    刻意保持紧凑：100 页摘要约 8k 字符，单次调用完全放得下。
    """
    lines = []
    for page in pages:
        parts = ["[{}]".format(page.page_index)]
        if page.doc_type:
            parts.append("类型={}".format(page.doc_type))
        if page.position_hint:
            parts.append("位置={}".format(page.position_hint))
        parts.append("摘要：{}".format(page.summary or "（无）"))
        lines.append(" ".join(parts))
    return "\n".join(lines)
